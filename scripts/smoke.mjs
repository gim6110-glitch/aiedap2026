import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded'});
 assert(await page.locator('#login-form').isVisible(),'login form');
 await page.locator('#login-name').fill('테스트교사');
 await page.locator('#login-school').fill('연수테스트학교');
 await page.locator('#login-form button[type=submit]').click();
 assert(await page.locator('#app').isVisible(),'app visible');
 assert.match(await page.locator('#slide-count').innerText(),/83/);
 assert.equal(await page.locator('#lessons button[data-slide]').count(),83);
 await page.locator('#lessons button[data-slide="18"]').click();
 assert.match(await page.locator('#slide-title').innerText(),/성취기준/);
 await page.locator('#activity-form [data-key="aiStudentAction"]').fill('학생은 AI의 제안을 검토하고 교과 개념을 바탕으로 판단한다.');
 await page.waitForTimeout(450);
 await page.locator('#lessons button[data-slide="36"]').click();
 assert(await page.locator('#activity-form [data-key="type"]').count()===1,'stage 1 type');
 await page.locator('#lessons button[data-slide="76"]').click();
 assert(await page.locator('#activity-form [data-key="feedbackStrength"]').count()===1,'feedback panel');
 await page.locator('#activity-form [data-key="feedbackStrength"]').fill('학생의 판단 근거를 확인하는 활동이 인상적입니다.');
 await page.waitForTimeout(450);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#login-name').fill('테스트교사');
 await page.locator('#login-school').fill('연수테스트학교');
 await page.locator('#login-form button[type=submit]').click();
 await page.locator('#lessons button[data-slide="18"]').click();
 assert.match(await page.locator('#activity-form [data-key="aiStudentAction"]').inputValue(),/학생은 AI/);
 await page.locator('#lessons button[data-slide="76"]').click();
 assert.match(await page.locator('#activity-form [data-key="feedbackStrength"]').inputValue(),/인상적/);
 await page.locator('#btn-result').click();
 assert(await page.locator('#view-result').isVisible(),'result visible');
 assert.equal(await page.locator('#result-stages .result-stage').count(),9);
 assert.equal(errors.length,0,'browser page errors: '+errors.join('; '));
 console.log('PASS: login, 83 slides, stage 0, stage 1, feedback, autosave, refresh, result');
}finally{await browser.close();}
